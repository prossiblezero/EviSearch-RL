"""Recovery-Augmented Demonstrations (RAD): add read-a-distractor-then-move-on steps to the SFT demos.

Usage: python -m evisearch.data.recovery   -> data/release-prepared/sft_rad.jsonl, data/release-prepared/sft_rad.manifest.json
Diagnosis (docs/evolution.md): the teacher wrote the agent demonstrations while
seeing the reference answer and evidence, so 97.5% of demos read exactly the gold documents and never show a
wrong read. The student learned an unconditional read -> save -> answer script: after reading a distractor it
saves it 90-97% of the time and recovers only ~10% of the time; RL did not change this.
Construction (no API calls): for half of the general agent demos (deterministic by id hash), replay the demo in
the deterministic EvidenceEnv; just before the first assistant turn that reads a gold document, insert one extra
assistant turn that reads the highest-ranked unread non-gold document from the latest search results. All tool
observations are regenerated by execution; the final answer and saved evidence are unchanged (the distractor is
never saved). The injected turn carries zero loss, so the model is not taught to read distractors; it is taught
what to do after one. Prompt and tool-observation tokens keep zero loss. Category and example counts are unchanged.
"""
import copy
import hashlib
import json
from collections import Counter

from resources import ROOT, read_jsonl, setup_paths
from evisearch.environment import EvidenceEnv, MAX_SEQUENCE_TOKENS, task_prompt, tool_schemas

from evisearch.artifacts import PREPARED as OUT, SEEDS, TEACHER_SFT
FRACTION = 0.5


def selected(row_id):
    return int(hashlib.sha256(row_id.encode()).hexdigest()[:8], 16) / 0xFFFFFFFF < FRACTION


def execute(task, messages):
    """Re-execute every call; returns (messages with regenerated observations, env)."""
    env = EvidenceEnv()
    env.reset(task=task)
    out = list(messages[:2])
    cursor = 2
    while cursor < len(messages):
        message = copy.deepcopy(messages[cursor])
        assert message['role'] == 'assistant'
        out.append(message)
        cursor += 1
        calls = message.get('tool_calls') or []
        if not calls:
            env._submit(message.get('content', ''))
        for call in calls:
            function = call['function']
            observation = copy.deepcopy(messages[cursor])
            assert observation['role'] == 'tool' and observation.get('tool_call_id') == call.get('id')
            observation['content'] = env._dispatch(function['name'], function['arguments'])
            out.append(observation)
            cursor += 1
    return out, env


def injection(task, messages):
    """(index of the first assistant turn reading a gold doc, distractor alias) or None."""
    env = EvidenceEnv()
    env.reset(task=task)
    gold = {alias for alias, doc in env._by_id.items() if doc['id'] in set(task['support_ids'])}
    # Never inject a document the demo itself reads later (it may be saved, e.g. a non-gold page kept by the teacher).
    read_anywhere = {c['function']['arguments'].get('doc_id') for m in messages[2:]
                     for c in (m.get('tool_calls') or []) if c['function']['name'] == 'read'}
    latest, read = [], set(read_anywhere)
    cursor = 2
    while cursor < len(messages):
        message = messages[cursor]
        calls = message.get('tool_calls') or []
        reads = [c['function']['arguments'].get('doc_id') for c in calls if c['function']['name'] == 'read']
        if any(d in gold for d in reads):
            candidates = [d for d in latest if d not in gold and d not in read]
            return (cursor, candidates[0]) if candidates else None
        cursor += 1
        for call in calls:
            observation = json.loads(messages[cursor]['content'])
            if call['function']['name'] == 'search' and 'documents' in observation:
                latest = [d['doc_id'] for d in observation['documents']]
            if call['function']['name'] == 'read' and 'doc_id' in observation:
                read.add(observation['doc_id'])
            cursor += 1
    return None


def encode(tok, messages, schemas, masked_assistant):
    encoded = tok.apply_chat_template(messages, tools=schemas, enable_thinking=False,
                                      return_dict=True, return_assistant_tokens_mask=True)
    ids, mask = encoded['input_ids'], list(encoded['assistant_masks'])
    spans, start = [], None
    for i, value in enumerate(mask + [0]):
        if value and start is None:
            start = i
        elif not value and start is not None:
            spans.append((start, i))
            start = None
    assistants = sum(m['role'] == 'assistant' for m in messages)
    assert len(spans) == assistants, (len(spans), assistants)
    if masked_assistant is not None:
        s, e = spans[masked_assistant]
        mask[s:e] = [0] * (e - s)
    if len(ids) > MAX_SEQUENCE_TOKENS:
        return None
    return dict(input_ids=ids, labels=[t if m else -100 for t, m in zip(ids, mask)],
                tokens=len(ids), assistant_tokens=sum(mask))


def main():
    setup_paths()
    from evisearch.model import tokenizer
    tok, schemas = tokenizer(), tool_schemas()
    pool = {t['id']: t for t in read_jsonl(SEEDS / 'sft_pool.jsonl')}
    rows = read_jsonl(TEACHER_SFT)
    stats = Counter()
    out = []
    for row in rows:
        if row['category'] != 'agent_general' or not selected(row['id']):
            out.append(row)
            continue
        stats['selected'] += 1
        task = pool[row['parent_id']]
        assert row['messages'][:2] == task_prompt(task)
        original, env0 = execute(task, row['messages'])
        assert [m['content'] for m in original if m['role'] == 'tool'] == \
               [m['content'] for m in row['messages'] if m['role'] == 'tool'], 'Demo does not replay exactly'
        found = injection(task, row['messages'])
        if not found:
            stats['no_injection_point'] += 1
            out.append(row)
            continue
        index, distractor = found
        injected = dict(role='assistant', content='', tool_calls=[dict(
            type='function', id=f'call_rad_{row["id"][:12]}',
            function=dict(name='read', arguments=dict(doc_id=distractor, page=0)))])
        observation = dict(role='tool', tool_call_id=injected['tool_calls'][0]['id'], name='read', content='')
        messages, env = execute(task, row['messages'][:index] + [injected, observation] + row['messages'][index:])
        before, after = env0._score(env0.final_answer), env._score(env.final_answer)
        keys = ('em', 'f1', 'format_valid', 'references_valid', 'evidence_f1', 'evidence_coverage', 'evidence_precision')
        if any(before[k] != after[k] for k in keys) or any('"error"' in m['content'] for m in messages if m['role'] == 'tool'):
            stats['changed_outcome_or_error'] += 1
            out.append(row)
            continue
        position = next(i for i, m in enumerate(messages) if m['role'] == 'assistant' and (m.get('tool_calls') or [{}])[0].get('id') == injected['tool_calls'][0]['id'])
        masked = sum(m['role'] == 'assistant' for m in messages[:position + 1]) - 1
        encoded = encode(tok, messages, schemas, masked)
        if encoded is None:
            stats['too_long'] += 1
            out.append(row)
            continue
        injected_doc = env._by_id[distractor]['id']
        assert injected_doc not in set(task['support_ids'])
        if any(p['source_id'] == injected_doc for p in env.selected_evidence.values()):
            stats['distractor_saved'] += 1
            out.append(row)
            continue
        stats['augmented'] += 1
        out.append(dict(row, id=row['id'] + '-rad', construction='recovery_augmented_replay',
                        messages=messages, injected_distractor=distractor, masked_assistant_turn=masked, **encoded))
    assert len(out) == len(rows) and Counter(r['category'] for r in out) == Counter(r['category'] for r in rows)
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / 'sft_rad.jsonl'
    path.write_text(''.join(json.dumps(r, ensure_ascii=False) + '\n' for r in out))
    tokens = Counter()
    for r in out:
        tokens[r['category']] += r['assistant_tokens']
    manifest = dict(source_sha256=hashlib.sha256((TEACHER_SFT).read_bytes()).hexdigest(),
                    sha256=hashlib.sha256(path.read_bytes()).hexdigest(), rows=len(out),
                    conversations=dict(Counter(r['category'] for r in out)), assistant_tokens=dict(tokens),
                    original_assistant_tokens=dict(Counter({c: sum(r['assistant_tokens'] for r in rows if r['category'] == c)
                                                            for c in {r['category'] for r in rows}})),
                    construction=dict(stats), fraction=FRACTION,
                    max_tokens=max(r['tokens'] for r in out))
    (OUT / 'sft_rad.manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print(json.dumps(manifest, indent=2))


if __name__ == '__main__':
    main()
